"""契约制品规范化 - 统一行尾并加生成标记"""

from pathlib import Path

# 制品路径
TARGET = Path("contracts/http/dist/openapi.yaml")

# 生成标记
BANNER = b"# Generated by mise run bundle - do not edit manually\n"


def main() -> None:
    """规范行尾为 LF 并确保生成标记位于首行"""
    data = TARGET.read_bytes().replace(b"\r\n", b"\n")
    if not data.startswith(BANNER):
        data = BANNER + data

    TARGET.write_bytes(data)


if __name__ == "__main__":
    main()
